// defunctCAEntry bundles a curated defunct-CA distinguished name with its
// real historical NotBefore/NotAfter validity dates. We need both because
// (review F-RR-1) a censor with access to public CA records can compare a
// generated padding cert's Subject CN to its validity period: a cert
// claiming to be "VeriSign Class 3 ... G5" that was supposedly issued
// `time.Now() - 1 year` is provably impossible (real G5 roots were issued
// 2006-11-08), turning every padding cert into an instant detection signal.
// Anchoring NotBefore/NotAfter to the real CA's published validity period
// closes that oracle.
type defunctCAEntry struct {
	Subject   pkix.Name
	NotBefore time.Time
	NotAfter  time.Time
}

